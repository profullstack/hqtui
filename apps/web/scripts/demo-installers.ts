// Generates apps/web/public/demo/<language>.sh: one `curl -fsSL … | sh` installer per demo
// language, so each can be listed (and signed) as its own package on w3bs.org/packages.
// Each installer pins public/demo.sh by sha256 and installs `hqtui-demo-<language>`, a small
// command that runs that launcher for one language. Regenerate after changing demo.sh or
// bumping the version:  bun apps/web/scripts/demo-installers.ts   (--check fails if stale)
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dir, '..', '..', '..');
const publicDir = join(root, 'apps', 'web', 'public');
export const LANGUAGES = ['typescript', 'rust', 'go', 'python', 'zig', 'cpp', 'ruby', 'php', 'perl', 'nim', 'cobol'];

const version = JSON.parse(readFileSync(join(root, 'packages', 'hqtui', 'package.json'), 'utf8')).version as string;
const demoSha = createHash('sha256').update(readFileSync(join(publicDir, 'demo.sh'))).digest('hex');

export function installer(language: string): string {
  const command = `hqtui-demo-${language}`;
  return `#!/bin/sh
# Installs ${command}: the HQTUI ten-screen demo in ${language}, built from hqtui main by
# the hqtui.com/demo.sh launcher (pinned below by sha256) with your installed toolchain.
# Generated by apps/web/scripts/demo-installers.ts; do not edit by hand.
set -eu
VERSION=${version}
DEMO_SHA256=${demoSha}
fail() { printf '${command}: %s\\n' "$*" >&2; exit 1; }
command -v curl >/dev/null 2>&1 || fail 'curl is required'
bin=\${HQTUI_BIN_DIR:-\${HOME:?HOME must be set}/.local/bin}
share=\${XDG_DATA_HOME:-$HOME/.local/share}/hqtui-demo
mkdir -p "$bin" "$share"
tmp=$(mktemp "$share/demo.sh.XXXXXX")
trap 'rm -f "$tmp"' EXIT INT TERM
curl -fsSL https://hqtui.com/demo.sh -o "$tmp" || fail 'could not download https://hqtui.com/demo.sh'
if command -v sha256sum >/dev/null 2>&1; then got=$(sha256sum "$tmp" | cut -d' ' -f1)
else got=$(shasum -a 256 "$tmp" | cut -d' ' -f1); fi
[ "$got" = "$DEMO_SHA256" ] || fail "demo.sh does not match this installer (got $got); rerun the installer from hqtui.com"
mv "$tmp" "$share/demo-$DEMO_SHA256.sh"
trap - EXIT INT TERM
cat > "$bin/${command}" <<EOF
#!/bin/sh
# ${command} $VERSION: the HQTUI demo in ${language} (installed from hqtui.com/demo/${language}.sh).
case "\\\${1:-}" in --version|-V) echo "${command} $VERSION"; exit 0 ;; esac
# The launcher uses mise when it is installed and your own toolchain otherwise; a leading
# --mise or --system picks one.
manager=
case "\\\${1:-}" in --mise|--system) manager=\\$1; shift ;; esac
exec sh "$share/demo-$DEMO_SHA256.sh" \\$manager ${language} "\\$@"
EOF
chmod 0755 "$bin/${command}"
printf '${command} %s installed in %s\\n' "$VERSION" "$bin"
case ":\${PATH:-}:" in *":$bin:"*) ;; *) printf 'Add %s to your PATH to run ${command}.\\n' "$bin" ;; esac
printf 'Run: ${command}   (uses mise if installed, else your ${language} toolchain; --sim for a simulation, --snapshot without a terminal)\\n'
`;
}

if (import.meta.main) {
  const outDir = join(publicDir, 'demo');
  const check = process.argv.includes('--check');
  let stale = 0;
  mkdirSync(outDir, { recursive: true });
  for (const language of LANGUAGES) {
    const path = join(outDir, `${language}.sh`);
    const text = installer(language);
    if (check) {
      if (!existsSync(path) || readFileSync(path, 'utf8') !== text) {
        console.error(`stale: ${path}`);
        stale++;
      }
    } else writeFileSync(path, text, { mode: 0o644 });
  }
  if (stale) process.exit(1);
  console.log(`${LANGUAGES.length} demo installers ${check ? 'current' : 'written'} (hqtui ${version}, demo.sh ${demoSha.slice(0, 12)})`);
}
